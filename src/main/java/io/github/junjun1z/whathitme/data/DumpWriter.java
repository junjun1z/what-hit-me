package io.github.junjun1z.whathitme.data;

import java.io.File;
import java.io.IOException;
import java.io.OutputStreamWriter;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.List;
import java.util.Map;

import io.github.junjun1z.whathitme.config.WhmConfig;
import io.github.junjun1z.whathitme.text.RecapFormatter;

/** Writes whathitme_dump.csv: damage types, entities, effects with their properties and the custom settings. */
public final class DumpWriter {

    private DumpWriter() {}

    private static String csv(String s) {
        if (s == null) return "";
        if (s.indexOf(',') >= 0 || s.indexOf('"') >= 0 || s.indexOf('\n') >= 0) return '"' + s.replace("\"", "\"\"") + '"';
        return s;
    }

    private static String flags(int f) {
        StringBuilder sb = new StringBuilder();
        String[] names = {"bypasses_armor", "absolute", "magic", "fire", "explosion", "projectile", "through_shield", "ignores_iframes", "bypasses_creative"};
        for (int i = 0; i < names.length; i++) {
            if ((f & (1 << i)) != 0) {
                if (sb.length() > 0) sb.append(' ');
                sb.append(names[i]);
            }
        }
        return sb.toString();
    }

    /**
     * Every known damage id (vanilla damage types, mob:&lt;entity&gt; for each registered living entity, and everything seen)
     * in the order: vanilla types, seen ids, mobs. Sorted inside each group for a stable file.
     */
    public static List<String> knownIds(List<Entry> entries) {
        java.util.Set<String> vanilla = new java.util.TreeSet<>();
        for (String t : Sources.VANILLA_TYPES) if (!"mob".equals(t) && !"player".equals(t)) vanilla.add("minecraft:" + t);
        java.util.Set<String> seen = new java.util.TreeSet<>();
        java.util.Set<String> mobs = new java.util.TreeSet<>();
        mobs.add("mob:minecraft:player");
        for (Entry e : entries) {
            if (e.type == Entry.DAMAGE) {
                if (e.id.startsWith("mob:")) mobs.add(e.id);
                else if (!vanilla.contains(e.id)) seen.add(e.id);
            }
        }
        for (net.minecraftforge.fml.common.registry.EntityEntry ee : net.minecraftforge.fml.common.registry.ForgeRegistries.ENTITIES.getValuesCollection()) {
            if (ee.getRegistryName() == null || ee.getEntityClass() == null) continue;
            if (net.minecraft.entity.EntityLivingBase.class.isAssignableFrom(ee.getEntityClass())) mobs.add("mob:" + ee.getRegistryName());
        }
        List<String> out = new java.util.ArrayList<>(vanilla);
        out.addAll(seen);
        out.addAll(mobs);
        return out;
    }

    /** Writes config/whathitme/hint_template.cfg: hintMap / renameMap blocks with every known id and an empty value */
    public static int writeTemplate(File file, List<Entry> entries) throws IOException {
        List<String> ids = knownIds(entries);
        File dir = file.getParentFile();
        if (dir != null && !dir.isDirectory()) dir.mkdirs();
        try (Writer w = new OutputStreamWriter(Files.newOutputStream(file.toPath()), StandardCharsets.UTF_8)) {
            w.write("# What Hit Me? - hintMap / renameMap template (generated by /whm dump)\n");
            w.write("#\n");
            w.write("# Copy the blocks you need into the \"filters\" category of whathitme-common.cfg (pack wide)\n");
            w.write("# or whathitme-client.cfg (personal), then fill in the values after '='.\n");
            w.write("# Lines with an empty value are ignored, so you can paste the whole list and fill in only some.\n");
            w.write("# A value can be plain text (& color codes work) or lang:<translation.key> to translate it\n");
            w.write("# with a resource pack. Ids may use * wildcards, e.g. mob:lycanitesmobs:*\n");
            w.write("# Vanilla damage types first, then other damage seen in this world, then every registered mob.\n\n");
            for (String list : new String[] {"hintMap", "renameMap"}) {
                w.write("    S:" + list + " <\n");
                for (String id : ids) w.write("        " + id + " = \n");
                w.write("     >\n\n");
            }
        }
        return ids.size();
    }

    /** @return number of entries written */
    public static int write(File file, List<Entry> entries, WhmConfig.Base... configs) throws IOException {
        int n = 0;
        try (Writer w = new OutputStreamWriter(Files.newOutputStream(file.toPath()), StandardCharsets.UTF_8)) {
            w.write('﻿');
            w.write("category,id,name,mod_id,mod_name,properties,times_seen,custom_name,custom_tip,ignored\n");
            for (Entry e : entries) {
                String cat = e.type == Entry.DAMAGE ? "damage" : e.type == Entry.MOB ? "entity" : "effect";
                String name = e.type == Entry.DAMAGE && !e.id.startsWith("mob:") ? RecapFormatter.pretty(e.name) : e.name;
                String props = e.type == Entry.DAMAGE ? flags(e.flags) : e.type == Entry.EFFECT ? ((e.flags & 1) != 0 ? "harmful" : "beneficial") : "";
                String ren = "";
                String tip = "";
                boolean ign = false;
                for (WhmConfig.Base c : configs) {
                    if (c == null) continue;
                    if (c.renameMap.containsKey(e.id)) ren = c.renameMap.get(e.id);
                    if (c.hintMap.containsKey(e.id)) tip = c.hintMap.get(e.id);
                    ign |= c.isIgnored(e.id);
                }
                w.write(csv(cat) + ',' + csv(e.id) + ',' + csv(name) + ',' + csv(e.modId) + ',' + csv(e.modName) + ',' + csv(props) + ','
                    + (e.type == Entry.DAMAGE ? String.valueOf(e.count) : "") + ',' + csv(ren) + ',' + csv(tip) + ',' + (ign ? "true" : "") + '\n');
                n++;
            }
            for (WhmConfig.Base c : configs) {
                if (c == null) continue;
                String src = c instanceof WhmConfig.Common ? "common" : "client";
                for (String s : c.ignoredDamageIds) w.write("setting_" + src + ",ignoredDamageIds," + csv(s) + ",,,,,,,\n");
                for (Map.Entry<String, String> e : c.renameMap.entrySet()) w.write("setting_" + src + ",renameMap," + csv(e.getKey()) + ",,,,," + csv(e.getValue()) + ",,\n");
                for (Map.Entry<String, String> e : c.hintMap.entrySet()) w.write("setting_" + src + ",hintMap," + csv(e.getKey()) + ",,,,,," + csv(e.getValue()) + ",\n");
                for (WhmConfig.Flag f : WhmConfig.Flag.values()) w.write("setting_" + src + "," + f.key + "," + ((c.mask & f.bit()) != 0) + ",,,,,,,\n");
            }
        }
        return n;
    }
}
